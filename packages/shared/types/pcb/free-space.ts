/**
 * Поиск свободного места на плате под подпись или логотип.
 *
 * Раньше свободную зону приходилось вычислять вручную по списку компонентов,
 * и это ошибка: габарит детали заметно больше её корпуса (у USB-C крепёжные
 * пятаки уходят далеко за корпус), поэтому надпись садилась на медь.
 *
 * Все координаты и размеры — в мм.
 */

export interface FreeSpaceRequest {
    /** Требуемый размер площадки. */
    width: number;
    height: number;
    /** Слой, на котором ищем: занятость считается по нему и по сквозным элементам. */
    layer?: 'top' | 'bottom';
    /** Искать ближе к этой детали. */
    near_designator?: string;
    /** Либо ближе к этой точке. По умолчанию — центр платы. */
    near_x?: number;
    near_y?: number;
    /** Зазор до ближайшего препятствия. */
    clearance?: number;
    /** Отступ от края платы. */
    edge_margin?: number;
}

export interface FreeSpaceResult {
    found: boolean;
    /** Центр найденной площадки. */
    x?: number;
    y?: number;
    /** Расстояние от точки притяжения до найденного центра. */
    distance?: number;
    /** Сколько препятствий участвовало в проверке. */
    obstacles: number;
    reason?: string;
}
